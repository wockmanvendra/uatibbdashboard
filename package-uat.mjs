// Builds the UAT deployment package (Ubuntu + Apache + PM2, uatIbbInsights.wockhardt.com):
//
//   node package-uat.mjs
//
// Output, in deploy/uat/ (git-ignored — the API .env holds secrets):
//   ibb-insights-web/          the frontend: copy to /var/www/ibb-insights/web
//   ibb-insights-api/          the API with its runtime node_modules and .env:
//                              copy to /var/www/ibb-insights/api, start with PM2
//   apache/uatibbinsights.conf the Apache site
//   ibb-insights-web.tar.gz, ibb-insights-api.tar.gz   the same, for scp
//   DEPLOYMENT_UAT.md          the guide (copied from deploy-uat-guide.md)
//
// The API .env is made from divperf-api/.env with the UAT settings below; the
// retired sign-in settings (user database, session secret, SMS/SMTP, Infinity)
// are left out. No secret is printed. Sign-in is the Central User Service:
// CENTRAL_API_KEY comes from divperf-api/.env, or is set on the server.
import { execSync } from 'node:child_process';
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = import.meta.dirname;
const OUT = join(ROOT, 'deploy', 'uat');
const WEB = join(OUT, 'ibb-insights-web');
const API = join(OUT, 'ibb-insights-api');
const run = (cmd, cwd) => execSync(cmd, { cwd, stdio: 'inherit' });

// UAT settings, over divperf-api/.env.
const UAT = {
  PORT: '8787',
  HOST: '127.0.0.1',
  NODE_ENV: 'production',
  DATA_SOURCE: 'synapse-direct',
  USE_MOCK_DATA: 'false',
  // Views are cached in the API process and rebuilt when the data changes.
  CACHE_DRIVER: 'memory',
  CORS_ORIGIN: 'https://uatIbbInsights.wockhardt.com,http://uatIbbInsights.wockhardt.com',
  LOG_LEVEL: 'info',
  CENTRAL_USER_SERVICE_URL: 'https://users.wockregenerative.com',
  CENTRAL_CLIENT_ID: 'ibb-insights',
};

/** Settings of the retired sign-in (sales_dash_user_db): not carried to UAT. */
const RETIRED = /^(USER_DATABASE_URL|JWT_SECRET|SESSION_MAX_HOURS|OTP_EXPIRY_MINUTES|SMS_.*|SMTP_.*|EMAIL_FROM|INFINITY_.*)$/;

console.log('1/6 Building the API and the frontend...');
run('npm run build --silent', join(ROOT, 'divperf-api'));
run('npm run build --silent', join(ROOT, 'divperf-web'));

console.log('2/6 Fresh output folder...');
// Empty the folder rather than delete it: Windows refuses to delete a folder
// that a shell or editor has open.
mkdirSync(OUT, { recursive: true });
for (const n of readdirSync(OUT)) rmSync(join(OUT, n), { recursive: true, force: true });
mkdirSync(join(OUT, 'apache'), { recursive: true });

console.log('3/6 Frontend...');
// web.config is IIS-only; Apache gets its own site file.
cpSync(join(ROOT, 'divperf-web', 'dist'), WEB, {
  recursive: true,
  filter: (src) => !src.endsWith('web.config'),
});

console.log('4/6 API...');
cpSync(join(ROOT, 'divperf-api', 'dist', 'src'), join(API, 'dist', 'src'), { recursive: true });
for (const f of ['package.json', 'package-lock.json']) {
  cpSync(join(ROOT, 'divperf-api', f), join(API, f));
}

// .env: every current key from divperf-api/.env, with the UAT overrides.
// Written without inline comments, and with values quoted where they hold a
// "#" or a space, so any Node 20.6+ --env-file parser reads them the same.
const env = {};
for (const line of readFileSync(join(ROOT, 'divperf-api', '.env'), 'utf8').split(/\r?\n/)) {
  const m = line.match(/^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*?)\s*$/);
  if (!m || RETIRED.test(m[1])) continue;
  let v = m[2];
  if (!/^["'`]/.test(v)) v = v.replace(/\s+#.*$/, ''); // drop an inline comment
  env[m[1]] = v.replace(/^(["'`])(.*)\1$/, '$2');
}
Object.assign(env, UAT);
env.CENTRAL_API_KEY ??= '';
env.ALL_DIVISION_MOBILES ??= '';
if (!env.CENTRAL_API_KEY) console.warn('CENTRAL_API_KEY is empty: set it in the server .env before starting the API.');
const quote = (v) => (/[#\s"'`]/.test(v) ? (v.includes("'") ? `"${v}"` : `'${v}'`) : v);
writeFileSync(
  join(API, '.env'),
  '# UAT settings for the IBB Insights API. Generated by package-uat.mjs.\n' +
    '# Keep this file private (chmod 600).\n' +
    Object.entries(env).map(([k, v]) => `${k}=${quote(v)}`).join('\n') + '\n',
);
writeFileSync(
  join(API, '.env.example'),
  readFileSync(join(ROOT, 'divperf-api', '.env.example'), 'utf8'),
);

writeFileSync(
  join(API, 'ecosystem.config.cjs'),
  `// PM2 process for the IBB Insights API (UAT).
//   pm2 start ecosystem.config.cjs     first time
//   pm2 reload ibb-insights-api        after copying a new build
// Settings come from .env in this folder (Node's --env-file, Node 20.6+).
module.exports = {
  apps: [
    {
      name: 'ibb-insights-api',
      cwd: __dirname,
      // start.js, not server.js: server.js starts itself only when Node runs it
      // directly, and PM2 runs scripts through its own wrapper.
      script: 'dist/src/start.js',
      node_args: '--env-file=.env',
      exec_mode: 'fork',
      instances: 1,
      autorestart: true,
      max_restarts: 20,
      restart_delay: 5000,
      max_memory_restart: '1G',
      time: true,
      out_file: 'logs/out.log',
      error_file: 'logs/error.log',
      merge_logs: true,
    },
  ],
};
`,
);
mkdirSync(join(API, 'logs'));

console.log('5/6 Runtime packages (production only)...');
run('npm ci --omit=dev --no-audit --no-fund --ignore-scripts', API);
// Built on Windows, run on Ubuntu: fine only while no package has a native binary.
const natives = [];
const walk = (d) => {
  for (const n of readdirSync(d)) {
    const p = join(d, n);
    if (statSync(p).isDirectory()) walk(p);
    else if (n.endsWith('.node')) natives.push(p);
  }
};
walk(join(API, 'node_modules'));
if (natives.length) {
  console.warn('Native binaries found - run "npm ci --omit=dev" on the server instead:\n  ' + natives.join('\n  '));
}

console.log('6/6 Apache site, guide, archives...');
cpSync(join(ROOT, 'deploy-uat-apache.conf'), join(OUT, 'apache', 'uatibbinsights.conf'));
cpSync(join(ROOT, 'deploy-uat-guide.md'), join(OUT, 'DEPLOYMENT_UAT.md'));
run('tar -czf ibb-insights-web.tar.gz ibb-insights-web', OUT);
run('tar -czf ibb-insights-api.tar.gz ibb-insights-api', OUT);

console.log(`Done: ${OUT}`);
